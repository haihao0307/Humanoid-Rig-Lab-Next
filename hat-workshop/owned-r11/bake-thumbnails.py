"""Build-time previews of default procedural hats. Does not bake runtime geometry or materials."""
from pathlib import Path
from functools import partial
from http.server import ThreadingHTTPServer,SimpleHTTPRequestHandler
import threading,argparse,json,base64,io,hashlib,time
from PIL import Image,ImageStat
from playwright.sync_api import sync_playwright
R=Path(__file__).resolve().parent
P=argparse.ArgumentParser();P.add_argument('--source',required=True);A=P.parse_args()
server=ThreadingHTTPServer(('127.0.0.1',0),partial(SimpleHTTPRequestHandler,directory=str(R)));threading.Thread(target=server.serve_forever,daemon=True).start()
report={'source':A.source,'passed':False,'scope':'default catalogue pictures only, generated by our own source; no reference images or baked runtime mesh','records':[]}
try:
 with sync_playwright() as pw:
  b=pw.chromium.launch(headless=True,args=['--no-sandbox','--enable-unsafe-swiftshader','--use-angle=swiftshader'])
  page=b.new_page(viewport={'width':1000,'height':720});errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
  t=time.perf_counter();page.goto(f'http://127.0.0.1:{server.server_port}/index.html#hat=field',wait_until='domcontentloaded')
  page.wait_for_function('window.ownedHat&&ownedHat.ready()&&ownedHat.stats().thumbs===11',timeout=180000)
  assert page.evaluate('ownedHat.source')==A.source
  assert page.evaluate('ownedHat.stats().metrics.thumbnailMode')=='generated-default-renders'
  images=page.locator('.hat-card').evaluate_all('(cards)=>Object.fromEntries(cards.map(c=>[c.dataset.id,c.querySelector("img").src]))')
  assert len(images)==11
  for id,data in images.items():
   assert data.startswith('data:image/webp;base64,')
   raw=base64.b64decode(data.split(',')[1],validate=True);image=Image.open(io.BytesIO(raw)).convert('RGB')
   assert image.size==(220,146) and sum(ImageStat.Stat(image).var)>40
   report['records'].append({'id':id,'bytes':len(raw),'sha256':hashlib.sha256(raw).hexdigest(),'width':220,'height':146})
  assert not errors and not page.evaluate('ownedHat.stats().errors')
  report.update(passed=True,wallMS=(time.perf_counter()-t)*1000)
  (R/'PRESET_THUMBNAILS.json').write_text(json.dumps({'version':'HAT-R11.0','sourceSha':A.source,'images':images},separators=(',',':')))
  b.close()
finally:
 server.shutdown();(R/'qa').mkdir(exist_ok=True);(R/'qa/thumbnail-bake.json').write_text(json.dumps(report,indent=2));print(json.dumps(report),flush=True)
